#include <iostream>
using namespace std;

int main(){
    cout << "OOP Quick Notes Why OOP?" << endl;

    // OOP helps manage complex programs and models real-world entities
    // It improves reusability, maintainability, and clarity

    // Procedure-Oriented Programming (POP)
    // - Focuses on functions, not data
    // - Step-by-step procedures
    // - Hard to manage large code, limited reusability

    // Object-Oriented Programming (OOP)
    // - Focuses on objects (data + methods together)
    // - Examples: C++, Java, Python

    // Basic Concepts of OOP:
    // 1. Class      -> Blueprint for objects
    // 2. Object     -> Instance of a class
    // 3. Encapsulation -> Data + methods together; control access
    // 4. Abstraction -> Hide complexity, show essentials
    // 5. Inheritance -> Reuse code from another class
    // 6. Polymorphism -> Same function behaves differently (Overloading/Overriding)

    // Benefits of OOP:
    // - Easier code maintenance
    // - Reusable and modular code
    // - Better data security
    // - Scalable for large programs

    return 0;
}
